#!/usr/bin/env node
// The Homebrew formula for OpenBridge (`brew install nubisco/tap/openbridge`),
// written from the npm release that Publish to npm just made. It lives in the
// nubisco/homebrew-tap repository, beside Alter's, and the Homebrew workflow
// commits it there after every release.
//
// Unlike Alter there is no archive per platform: the formula installs the same
// npm package every other install method uses, on Homebrew's own Node. The
// in-app updater recognises the Cellar and leaves updates to `brew upgrade`.
//
// Usage: node scripts/homebrew-formula.mjs <version> <sha256 of the npm tarball>

export function homebrewFormula({ version, sha256 }) {
  return `# Generated by openbridge/scripts/homebrew-formula.mjs on each release. Do not edit by hand.
class Openbridge < Formula
  desc "Local-first home automation bridge, Homebridge-compatible"
  homepage "https://docs.nubisco.io/openbridge/"
  url "https://registry.npmjs.org/@nubisco/openbridge/-/openbridge-${version}.tgz"
  sha256 "${sha256}"
  license "MIT"

  depends_on "node"

  def install
    system "npm", "install", *std_npm_args
    bin.install_symlink libexec.glob("bin/*")

    # node-pty, behind the dashboard's shell pane, ships prebuilt binaries for
    # every platform. Keep this one's, and make its spawn-helper executable:
    # Homebrew installs with --ignore-scripts, so the package's own postinstall
    # that does this never runs.
    native = "#{OS.kernel_name.downcase}-#{Hardware::CPU.intel? ? "x64" : "arm64"}"
    prebuilds = libexec/"lib/node_modules/@nubisco/openbridge/node_modules/node-pty/prebuilds"
    prebuilds.children.each { |dir| rm_r(dir) if dir.basename.to_s != native } if prebuilds.exist?
    helper = prebuilds/native/"spawn-helper"
    chmod 0755, helper if helper.exist?
  end

  # \`brew services start openbridge\` keeps it running and starts it at login.
  # npm stays on the PATH because the dashboard installs Homebridge plugins with it.
  service do
    run [opt_bin/"openbridge"]
    environment_variables PATH: std_service_path_env, OPENBRIDGE_INSTALL: "homebrew"
    keep_alive successful_exit: false
    process_type :background
    log_path var/"log/openbridge.log"
    error_log_path var/"log/openbridge.log"
  end

  def caveats
    <<~EOS
      Start OpenBridge now and at every login:
        brew services start openbridge
      Then open http://localhost:8582. Settings and pairing data live in ~/.openbridge.
      Update it with brew upgrade openbridge, not from the dashboard.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/openbridge --version")
  end
end
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [version, sha256] = process.argv.slice(2)
  if (!/^\d+\.\d+\.\d+$/.test(version ?? '') || !/^[0-9a-f]{64}$/.test(sha256 ?? '')) {
    console.error('Usage: node scripts/homebrew-formula.mjs <version> <sha256>')
    process.exit(1)
  }
  process.stdout.write(homebrewFormula({ version, sha256 }))
}
